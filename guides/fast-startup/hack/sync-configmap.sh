#!/usr/bin/env bash
#
# Regenerate the snapshot-scripts ConfigMap from the Python sources.
#
# The GKE overlay mounts these scripts from a ConfigMap so the checkpoint/restore
# sequencing can be iterated on without rebuilding a ~10 GB image. That means the
# YAML holds a second copy of the code, which has silently drifted from
# docker/scripts/snapshot/ before and cost real debugging time. Run this after any
# edit under docker/scripts/snapshot/ and commit the result.
#
#   guides/fast-startup/hack/sync-configmap.sh
#
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
src_dir="${repo_root}/docker/scripts/snapshot"
out="${repo_root}/guides/fast-startup/modelserver/gpu/vllm/gke/configmap.yaml"

# ConfigMap keys cannot contain "/", so nested modules are flattened here and
# remapped to their real paths by the volume's `items` in patch-gke.yaml.
#   key            source
declare -a entries=(
  "launcher.py    ${src_dir}/launcher.py"
  "providers.py   ${src_dir}/providers.py"
  "wrapper.py     ${src_dir}/vllm/wrapper.py"
  "worker.py      ${src_dir}/vllm/worker.py"
)

{
  cat <<'EOF'
# Generated by guides/fast-startup/hack/sync-configmap.sh -- do not edit.
# Source of truth is docker/scripts/snapshot/. Re-run the script after changing it.
apiVersion: v1
kind: ConfigMap
metadata:
  name: snapshot-scripts
data:
EOF

  for entry in "${entries[@]}"; do
    read -r key src <<<"${entry}"
    [[ -f "${src}" ]] || { echo "missing source: ${src}" >&2; exit 1; }
    printf '  %s: |\n' "${key}"
    # Indent by four, but leave blank lines genuinely blank: trailing whitespace
    # inside a literal block scalar is legal but noisy in diffs.
    awk '{ if (length($0) > 0) print "    " $0; else print "" }' "${src}"
  done
} >"${out}"

echo "wrote ${out}"
